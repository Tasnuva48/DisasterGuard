    private void btnAcceptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAcceptActionPerformed
        // TODO add your handling code here:
        VolunteerAlertDAO dao = new VolunteerAlertDAO();

        boolean success = dao.updateTaskStatus(taskId, username, "Accepted");

        if (success) {
            JOptionPane.showMessageDialog(this, "Task Accepted Successfully");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update task");
        }
    }//GEN-LAST:event_btnAcceptActionPerformed

    private void btnDeclineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeclineActionPerformed
        // TODO add your handling code here:
        VolunteerAlertDAO dao = new VolunteerAlertDAO();

        boolean success = dao.updateTaskStatus(taskId, username, "Rejected");

        if (success) {
            JOptionPane.showMessageDialog(this, "Task Rejected");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update task");
        }
    }//GEN-LAST:event_btnDeclineActionPerformed



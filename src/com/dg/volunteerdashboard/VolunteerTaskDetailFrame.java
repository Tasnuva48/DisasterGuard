    private void loadTaskDetails() {

        VolunteerAlertDAO dao = new VolunteerAlertDAO();

        Task task = dao.getTaskDetail(taskId);

        if (task != null) {

            lblAlertTitle.setText(task.getAlertTitle());
            lblTaskTitle.setText(task.getTaskTitle());
            txtDescription.setText(task.getTaskDescription());
            txtDescription.setCaretPosition(0);

            if (task.getDeadline() != null) {
                lblDeadline.setText(task.getDeadline().toString());
            } else {
                lblDeadline.setText("No deadline");
            }

        }
    }


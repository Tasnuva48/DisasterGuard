    private boolean validateQualificationForm() {

        if (AdminHigherEducationalQualification.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select highest educational qualification.");
            return false;
        }

        if (AdminMajorSubject.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter major subject or field.");
            return false;
        }

        if (AdminUniversity.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter university or institution name.");
            return false;
        }

        if (AdminOfficialDesignation.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter official designation.");
            return false;
        }

        if (AdminOrganization.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter organization or department name.");
            return false;
        }

        if (AdminOrganizationType.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select organization type.");
            return false;
        }

        if (AdminOfficialIDNumber.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter official ID number.");
            return false;
        }

        if (AdminDateOfJoining.getSelectedIndex() == 0
                || AdminMonthOfJoining.getSelectedIndex() == 0
                || AdminYearOfJoining.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select complete joining date.");
            return false;
        }

        return true;
    }


    private void AdminQualificationNextButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AdminQualificationNextButtonActionPerformed
        // TODO add your handling code here:
        
        if (!validateQualificationForm()) {
            return;
        }

        MainAdminFrame frame = (MainAdminFrame) SwingUtilities.getWindowAncestor(this);
        AdminData admin=frame.getAdminData();
        admin.setHigherEducation(
            AdminHigherEducationalQualification.getSelectedItem().toString()
    );

    admin.setMajorSubjectField(
            AdminMajorSubject.getText().trim()
    );

    admin.setUniversityInstitution(
            AdminUniversity.getText().trim()
    );

    // ===== Official Designation & Organization =====
    admin.setOfficialDesignation(
            AdminOfficialDesignation.getText().trim()
    );

    admin.setOrganizationDepartment(
            AdminOrganization.getText().trim()
    );

    admin.setOrganizationType(
            AdminOrganizationType.getSelectedItem().toString()
    );

    admin.setEmployeeOfficialIdNumber(
            AdminOfficialIDNumber.getText().trim()
    );

    // ===== Date of Joining =====
    admin.setDateOfJoiningDay(
            Integer.parseInt(AdminDateOfJoining.getSelectedItem().toString())
    );

    admin.setDateOfJoiningMonth(
            AdminMonthOfJoining.getSelectedItem().toString()
    );

    admin.setDateOfJoiningYear(
            Integer.parseInt(AdminYearOfJoining.getSelectedItem().toString())
    );
        frame.showCard("SKILLS");
    }//GEN-LAST:event_AdminQualificationNextButtonActionPerformed

